import chainlit as cl
from dotenv import load_dotenv
load_dotenv()
from langchain_core.messages import HumanMessage
from agent import app_graph
import asyncio

@cl.on_chat_start
async def on_chat_start():
    """
    On chat start, display a welcoming message explaining the tool's capabilities.
    """
    welcome_message = (
        "Welcome to the **Omni-Meeting Memory Agent**! 🚀\n\n"
        "I can help you recall meeting history or extract action items from our past discussions.\n"
        "Feel free to ask me questions like:\n"
        "- *What action items are assigned to Bob?*\n"
        "- *When was the timeline extended?*"
    )
    await cl.Message(content=welcome_message).send()

@cl.on_message
async def on_message(message: cl.Message):
    """
    Handle user messages, display a loading spinner while the graph executes, 
    and stream the final response back to the chat window.
    """
    # Create an empty message to stream the response into later
    msg = cl.Message(content="")
    
    # Display a loading spinner/step in Chainlit UI while the graph executes
    async with cl.Step("Agent reasoning graph is executing...") as step:
        # Prepare the input for the LangGraph state machine
        inputs = {"messages": [HumanMessage(content=message.content)]}
        
        # Execute the graph asynchronously
        result = await app_graph.ainvoke(inputs)
        
        # The classified intent can be shown in the UI step to provide transparency
        intent = result.get("intent", "Unknown")
        step.output = f"Graph execution complete. Routed as: {intent}"

    # Extract the final response generated by the Synthesizer or Extractor node
    final_response = result.get("final_response", "Sorry, I could not process that request.")
    
    # Stream the final response back to the chat window
    for chunk in final_response.split(" "):
        await msg.stream_token(chunk + " ")
        await asyncio.sleep(0.02)  # Slight delay for a smoother streaming effect
        
    # Finalize the message update
    await msg.update()
